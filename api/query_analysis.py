def _is_shared_scope_term(current: str, candidate: str, term: str) -> bool:
    pair = frozenset({current, candidate})
    normalized_term = normalize(term)
    return normalized_term in {
        normalize(item) for item in SHARED_MODULE_SCOPE_TERMS.get(pair, ())
    }


def _explicit_out_of_scope_topic(normalized: str, current_score: int) -> tuple[str, list[str]] | None:
    """Return a high-signal external topic without blocking normal chat.

    ``assess_module_scope`` must distinguish an open conversation opener from a
    concrete task.  A message such as ``me ajuda`` has no topic and remains
    conversational; ``quero fazer pão`` has a concrete, recognizable topic and
    must stop at the module boundary before any provider is called.
    """

    if current_score > 0:
        return None
    for topic, terms in OUT_OF_SCOPE_TOPIC_TERMS:
        matched = [term for term in terms if normalize(term) in normalized]
        if matched:
            return topic, matched[:4]
    return None


