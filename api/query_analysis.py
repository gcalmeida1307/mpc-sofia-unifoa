def is_explicit_evidence_request(question: str) -> bool:
    """Return whether the user explicitly anchored the request to a source.

    Scope protection must not block a law, manual or file that intentionally
    lives in the active module, even when its subject uses vocabulary from a
    different domain.  This is the exception to the cross-domain gate.
    """

    normalized = normalize(question)
    return _has_explicit_evidence_request(normalized) or bool(
        re.search(r"\b[\w-]+\.(?:md|txt|pdf|docx|xlsx|csv|xml|json)\b", normalized)
    ) or any(
        re.search(rf"\b{re.escape(marker)}\b", normalized)
        if re.fullmatch(r"[\wÀ-ÿ]+", marker)
        else marker in normalized
        for marker in (
            "manual",
            "norma",
            "lei",
            "vade",
            "saae",
            "acordo coletivo",
            "convencao coletiva",
        )
    )


def _has_conversation_follow_up(
    question: str, history: list[dict[str, str]] | None
) -> bool:
    """Keep only genuinely conversational continuations on the chat route.

    The old implementation looked only at the last assistant message.  Once
    Sofia asked ``me conte o que aconteceu``, every next user turn inherited
    the conversation route, including concrete legal/technical questions.  A
    follow-up may remain conversational only when the current turn is short
    and does not contain an interrogative or a domain task marker.
    """

    if not history:
        return False
    normalized = normalize(question).strip()
    words = normalized.split()
    if len(words) > 7:
        return False
    if any(
        marker in normalized
        for marker in (
            "o que ",
            "qual ",
            "quais ",
            "como ",
            "por que ",
            "porque ",
            "quando ",
            "onde ",
            "quanto ",
            "quantos ",
            "quantas ",
            "e possivel",
            "é possível",
            "fale sobre",
            "explique",
            "defina",
            "resuma",
            "compare",
            "documento",
            "arquivo",
            "lei",
            "artigo",
            "norma",
            "acordo",
            "jornada",
            "hora extra",
            "tosse",
            "gripe",
            "zabbix",
        )
    ):
        return False
    for item in reversed(history[-6:]):
        if item.get("role") != "assistant":
            continue
        text = normalize(str(item.get("content", "")))
        if any(
            marker in text
            for marker in (
                "me conte",
                "o que aconteceu",
                "qual situacao",
                "qual situação",
                "pode explicar",
                "conte mais",
                "como posso ajudar",
            )
        ):
            return True
        break
    return False


def recent_documentary_answer(history: list[dict[str, str]] | None) -> str:
    """Return the latest bounded assistant answer that carries local evidence."""

    for item in reversed((history or [])[-8:]):
        if item.get("role") != "assistant":
            continue
        content = str(item.get("content", "")).strip()
        normalized = normalize(content)
        if any(marker in normalized for marker in ("fontes e trechos", "base documental", "fato documentado", "documento local")):
            return content[:2200]
    return ""


def recent_documentary_question(history: list[dict[str, str]] | None) -> str:
    """Return the user question that produced the latest local evidence."""

    items = list((history or [])[-8:])
    for index in range(len(items) - 1, -1, -1):
        item = items[index]
        if item.get("role") != "assistant":
            continue
        content = str(item.get("content", ""))
        if not any(marker in normalize(content) for marker in ("fontes e trechos", "base documental", "fato documentado", "documento local")):
            continue
        for previous in reversed(items[:index]):
            if previous.get("role") == "user" and str(previous.get("content", "")).strip():
                return str(previous["content"]).strip()[:1600]
    return ""


def requested_exact_term(question: str) -> str:
    """Extract the literal subject of a ``qual linha/onde está`` request."""

    text = str(question or "").strip()
    if not re.search(r"\b(?:linha|linhas|line|lines)\b", normalize(text)):
        return ""
    quoted = re.findall(r"[\"“”']([^\"“”']{3,240})[\"“”']", text)
    if quoted:
        return re.sub(r"\s+", " ", quoted[-1]).strip(" .,:;?!")
    match = re.search(r"(?:termo|trecho|texto)\s+(?:aqui)?\s*[?:-]?\s*(.+)$", text, flags=re.IGNORECASE)
    if not match:
        return ""
    candidate = re.sub(r"\s+", " ", match.group(1)).strip(" .,:;?!")
    if not candidate or re.fullmatch(r"\d+(?:\s*(?:-|a|até|to)\s*\d+)?", candidate, flags=re.IGNORECASE):
        return ""
    return candidate[:240]


